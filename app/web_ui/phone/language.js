let language = 'cs';
const index = ['en','sk','de','hi'];
export function useLanguage(value) {
  language = value;
}

export function t(value) {
  if (typeof value!=='string') return value;
  if (vocabulary[value]) return vocabulary[value][index.indexOf(language)] ?? value;
  const numbered = /^(Průchod|Stáhnout|Plán za měsíc|Plán skupiny|Vybráno úvazků|Plán)([ ·]+)(.+)$/.exec(value);
  if (numbered) return t(numbered[1])+numbered[2]+t(numbered[3]);
  return value;
}
